#!/usr/bin/env python3
"""Bundles src/*.luau into one ModuleScript source at dist/uniUI.luau.

The result can be pasted into a single ModuleScript in Studio. Each source
module is wrapped in a function and loaded through a small local require.

Usage: python3 tools/bundle.py [--check]
  --check  exit non-zero if dist/uniUI.luau is out of date (for CI)
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "dist" / "uniUI.luau"

REQUIRE = re.compile(r"require\(script(?:\.Parent)?\.(\w+)\)")
EXPORT_TYPE = re.compile(r"^export type ", re.MULTILINE)
DIRECTIVE = re.compile(r"^--!\w+\s*\n", re.MULTILINE)
VERSION = re.compile(r'local VERSION = "([^"]+)"')


def module_body(path: Path) -> str:
    text = path.read_text()
    text = DIRECTIVE.sub("", text)
    # `export type` is only valid at the top level of a file.
    text = EXPORT_TYPE.sub("type ", text)
    text = REQUIRE.sub(lambda m: f'__require("{m.group(1)}")', text)
    return "\n".join(("\t" + line) if line else "" for line in text.splitlines())


def build() -> str:
    files = sorted(SRC.glob("*.luau"))
    names = {f.stem for f in files}
    if "init" not in names:
        sys.exit("bundle: src/init.luau not found")

    version = VERSION.search((SRC / "init.luau").read_text())
    version = version.group(1) if version else "unknown"

    parts = [
        "--!nocheck",
        f"-- uniUI {version} — single-file build. Generated by tools/bundle.py; do not edit.",
        "-- Install: create a ModuleScript named uniUI in ReplicatedStorage and paste this in.",
        "-- Source and docs: https://github.com/jgamestaken/uniUI",
        "",
        "local __modules = {}",
        "local __cache = {}",
        "",
        "local function __require(name)",
        "\tlocal cached = __cache[name]",
        "\tif cached == nil then",
        "\t\tcached = __modules[name]()",
        "\t\t__cache[name] = cached",
        "\tend",
        "\treturn cached",
        "end",
        "",
    ]
    for f in files:
        parts.append(f'__modules["{f.stem}"] = function()')
        parts.append(module_body(f))
        parts.append("end")
        parts.append("")
    parts.append('return __require("init")')
    return "\n".join(parts) + "\n"


def main() -> None:
    output = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != output:
            sys.exit("bundle: dist/uniUI.luau is out of date; run python3 tools/bundle.py")
        print("bundle: up to date")
        return
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(output)
    print(f"bundle: wrote {OUT.relative_to(ROOT)} ({len(output.splitlines())} lines)")


if __name__ == "__main__":
    main()
